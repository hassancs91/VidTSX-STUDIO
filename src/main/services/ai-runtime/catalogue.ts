export interface AiRuntimeCatalogueEntry {
  version: string;
  variant: AiRuntimeVariant;
  /** Primary URL first, mirrors after (download engine falls through on hard failure). */
  urls: readonly string[];
  /** sha256 of the zip. */
  sha256: string;
  /** Bytes of the zip. */
  bytes: number;
  /** Bytes once extracted (manifest.json excluded), for the disk guard. */
  bytesOnDisk: number;
  files: number;
  /** Folder inside the zip holding python.exe. */
  extractedDir: 'python';
  python: string;
  torch: string;
  /** CUDA runtime line bundled with torch, null for the CPU build. */
  cuda: string | null;
  /** Minimum NVIDIA driver for the bundled CUDA line, null for the CPU build. */
  minDriver: string | null;
  /**
   * Deepest relative path inside the extracted runtime, in characters. The
   * preflight refuses to install when len(root) + this + 1 > 259 on a Windows
   * without LongPathsEnabled (Stage 0 relocation finding).
   */
  maxRelativePathLength: number;
  /** sha256 of requirements.<variant>.lock (LF-normalised) the build was synced from. */
  lockSha256: string;
  licence: string;
}

