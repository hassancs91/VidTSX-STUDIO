/** Folder name of an installed runtime: `<version>-<variant>`. */
export function aiRuntimeDirName(version: string, variant: AiRuntimeVariant): string {
  return `${version}-${variant}`;
}

/** Download-task id per variant (one task at a time per variant). */
export function aiRuntimeDownloadId(variant: AiRuntimeVariant): string {
  return `ai-runtime-${variant}`;
}

/** "2.6 GB" / "267 MB" for UI labels. */
export function formatRuntimeBytes(bytes: number): string {
  if (bytes >= 1_000_000_000) return `${(bytes / 1_000_000_000).toFixed(1)} GB`;
  return `${Math.round(bytes / 1_000_000)} MB`;
}

const DIR_NAME_RE = /^(\d{4}\.\d{2}\.\d+)-(cu126|cpu)$/;

/** Parse `<version>-<variant>` back into its parts; null for anything else (e.g. `.tmp` staging). */
export function parseAiRuntimeDirName(name: string): { version: string; variant: AiRuntimeVariant } | null {
  const m = DIR_NAME_RE.exec(name);
  if (!m) return null;
  return { version: m[1], variant: m[2] as AiRuntimeVariant };
}
