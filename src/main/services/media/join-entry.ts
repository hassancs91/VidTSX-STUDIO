// The render entry for `join_clips`: a self-registering Remotion root written
// per run under `<appRoot>/.vidtsx-temp/joins/` (where `remotion` and the
// bundler's `@shared` alias resolve, as for Studio's export entry). The plan
// and the clip URLs are baked in as constants a wrapper component closes over:
// the in-main render passes no input props to a self-registering entry, and
// `remotion-renderer.ts` renders a manual composition object whose props ARE
// the input props, so `defaultProps` never reach the component (the first live
// run died on `plan` undefined). Clips are served by the bundle server's
// `/asset` route, the way `caption_video` serves its clip.

import fs from 'fs/promises';
import path from 'path';
import { randomUUID } from 'crypto';
import { getAppRoot } from '../../utils/paths';
import type { JoinPlan } from '../../../shared/media/join-plan';

export const JOIN_COMPOSITION_ID = 'join-clips';

export interface JoinEntry {
  entryPath: string;
  cleanup: () => Promise<void>;
}

/** The entry's source. Exposed for tests. */
export function joinEntrySource(plan: JoinPlan, sources: readonly string[]): string {
  return `// Generated by join_clips — the plan and the clip URLs are baked in.
import { Composition, registerRoot } from 'remotion';
import { JoinClipsComposition } from '@shared/media/JoinClipsComposition';

const PLAN = ${JSON.stringify(plan)};
const SOURCES = ${JSON.stringify(sources)};

const Joined = () => <JoinClipsComposition plan={PLAN} sources={SOURCES} />;

const Root = () => (
  <Composition
    id=${JSON.stringify(JOIN_COMPOSITION_ID)}
    component={Joined}
    durationInFrames={PLAN.durationInFrames}
    fps={PLAN.fps}
    width={PLAN.width}
    height={PLAN.height}
  />
);

registerRoot(Root);
`;
}

/** Write the entry for one join; `cleanup` removes it after the render. */
export async function createJoinEntry(plan: JoinPlan, videoPaths: readonly string[], bundlerPort: number): Promise<JoinEntry> {
  const dir = path.join(getAppRoot(), '.vidtsx-temp', 'joins');
  await fs.mkdir(dir, { recursive: true });
  const sources = videoPaths.map((p) => `http://127.0.0.1:${bundlerPort}/asset?path=${encodeURIComponent(p)}`);
  const entryPath = path.join(dir, `join-entry-${randomUUID().slice(0, 8)}.tsx`);
  await fs.writeFile(entryPath, joinEntrySource(plan, sources), 'utf-8');
  return {
    entryPath,
    cleanup: () => fs.unlink(entryPath).catch(() => undefined),
  };
}
