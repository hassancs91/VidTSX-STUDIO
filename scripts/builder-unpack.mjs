// The TSX builder's library set, unpacked from app.asar (TSX_BUILDER_DESIGN.md
// T4 Rev 2 item 4, P2 part 5).
//
// `check` bundles a piece with esbuild (shot-bundle.ts), and esbuild is a native
// binary: it cannot read inside app.asar, so in a packaged app it finds only
// what sits in app.asar.unpacked/node_modules (shot-import.ts bundleNodePaths).
// Every package of the set and everything they pull in must be unpacked.
//
// The list comes from the ONE constant (src/shared/tsx-engine/builder-libraries.ts),
// walked through each package.json's dependencies, optionalDependencies and
// peerDependencies as installed. Left out: `react` (always external to the bundle
// step) and `@types/*` (esbuild never reads them).
//
//   node scripts/builder-unpack.mjs --write   rewrite the generated block in electron-builder.yml
//   node scripts/builder-unpack.mjs --check   exit 1 when the block is stale (a vitest test runs this)
//   node scripts/builder-unpack.mjs           print the closure with sizes
//
// The packaged build re-checks the result: scripts/after-pack-check.cjs.

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LIBRARIES_TS = 'src/shared/tsx-engine/builder-libraries.ts';
const YML = 'electron-builder.yml';
export const BLOCK_BEGIN = '  # BEGIN builder-libraries (generated by scripts/builder-unpack.mjs --write; do not edit)';
export const BLOCK_END = '  # END builder-libraries';
const NOT_READ_BY_ESBUILD = (name) => name === 'react' || name.startsWith('@types/');

/** BUILDER_LIBRARIES as the app sees it (the TS module, transpiled; it imports nothing). */
export function loadBuilderLibraries(root = ROOT) {
  const require = createRequire(path.join(root, 'package.json'));
  const esbuild = require('esbuild');
  const source = fs.readFileSync(path.join(root, LIBRARIES_TS), 'utf8');
  const { code } = esbuild.transformSync(source, { loader: 'ts', format: 'cjs' });
  const module = { exports: {} };
  new Function('module', 'exports', 'require', code)(module, module.exports, require);
  return module.exports.BUILDER_LIBRARIES;
}

function findPackageDir(name, fromDir, root) {
  for (let dir = fromDir; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
    if (dir === root || path.dirname(dir) === dir) return null;
  }
}

/** Every installed package folder the set needs, relative to `root`, posix, sorted. */
export function builderLibraryClosure(root = ROOT) {
  const names = loadBuilderLibraries(root)
    .filter((lib) => !lib.builtIn)
    .map((lib) => lib.name);
  const seen = new Set();
  const missing = [];
  const visit = (name, fromDir) => {
    if (NOT_READ_BY_ESBUILD(name)) return;
    const dir = findPackageDir(name, fromDir, root);
    if (!dir) {
      missing.push(name);
      return;
    }
    if (seen.has(dir)) return;
    seen.add(dir);
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    for (const dep of Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies, ...pkg.peerDependencies })) {
      visit(dep, dir);
    }
  };
  for (const name of names) {
    if (!findPackageDir(name, root, root)) throw new Error(`${name} (builder-libraries.ts) is not installed`);
    visit(name, root);
  }
  const dirs = [...seen].map((dir) => path.relative(root, dir).split(path.sep).join('/')).sort();
  const packages = [...seen]
    .map((dir) => {
      const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
      return { name: pkg.name, version: pkg.version, needs: neededDroppedFolders(dir) };
    })
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  return { libraries: names, dirs, packages, missing: [...new Set(missing)].sort() };
}

/**
 * asarUnpack patterns: one per package NAME, wherever it lands. electron-builder
 * rebuilds the production tree and hoists differently from npm's dev layout
 * (d3's own d3-geo@3 sits under d3/ in dev and at the top in the package), so
 * a path from this machine's node_modules can miss the packaged copy.
 */
export function unpackPatterns(packages) {
  return [...new Set(packages.map((p) => p.name))].sort().map((name) => `**/node_modules/${name}/**`);
}

export function generatedBlock(root = ROOT) {
  const { packages } = builderLibraryClosure(root);
  return [BLOCK_BEGIN, ...unpackPatterns(packages).map((p) => `  - "${p}"`), BLOCK_END].join('\n');
}

/** electron-builder drops these top-level folders from every package unless onNodeModuleFile keeps them. */
export const DROPPED_TOP_LEVEL = ['test', 'tests', '__tests__', 'powered-test', 'example', 'examples'];

/** The dropped folders a package's `exports` map points into: they must ship (scripts/node-module-file.cjs). */
export function neededDroppedFolders(packageDir) {
  const pkg = JSON.parse(fs.readFileSync(path.join(packageDir, 'package.json'), 'utf8'));
  const exportsText = JSON.stringify(pkg.exports ?? '');
  return DROPPED_TOP_LEVEL.filter(
    (name) => fs.existsSync(path.join(packageDir, name)) && exportsText.includes(`./${name}/`),
  );
}

/** Every package (name@version → its folders) installed under `nodeModules`, at any depth. */
export function installedPackages(nodeModules) {
  const found = new Map();
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isDirectory() || entry.name.startsWith('.')) continue;
      const full = path.join(dir, entry.name);
      if (entry.name.startsWith('@')) {
        walk(full);
        continue;
      }
      const pkgFile = path.join(full, 'package.json');
      if (!fs.existsSync(pkgFile)) continue;
      try {
        const pkg = JSON.parse(fs.readFileSync(pkgFile, 'utf8'));
        if (pkg.name && pkg.version) {
          const id = `${pkg.name}@${pkg.version}`;
          found.set(id, [...(found.get(id) ?? []), full]);
        }
      } catch {
        /* not a package */
      }
      const nested = path.join(full, 'node_modules');
      if (fs.existsSync(nested)) walk(nested);
    }
  };
  if (fs.existsSync(nodeModules)) walk(nodeModules);
  return found;
}

function replaceBlock(yml, block) {
  const begin = yml.indexOf(BLOCK_BEGIN);
  const end = yml.indexOf(BLOCK_END);
  if (begin < 0 || end < begin) throw new Error(`${YML} has no generated builder-libraries block under asarUnpack`);
  return yml.slice(0, begin) + block + yml.slice(end + BLOCK_END.length);
}

function dirSize(dir) {
  let bytes = 0;
  let files = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules') continue; // nested packages are listed on their own
      const sub = dirSize(full);
      bytes += sub.bytes;
      files += sub.files;
    } else {
      bytes += fs.statSync(full).size;
      files += 1;
    }
  }
  return { bytes, files };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const ymlPath = path.join(ROOT, YML);
  const mode = process.argv[2];
  if (mode === '--write' || mode === '--check') {
    const yml = fs.readFileSync(ymlPath, 'utf8').replace(/\r\n/g, '\n');
    const next = replaceBlock(yml, generatedBlock());
    if (mode === '--write') {
      fs.writeFileSync(ymlPath, next);
      console.log(`builder-unpack: ${YML} block written`);
    } else if (next !== yml) {
      console.error(`builder-unpack: the asarUnpack block in ${YML} is stale: run node scripts/builder-unpack.mjs --write`);
      process.exit(1);
    } else {
      console.log('builder-unpack: ok');
    }
  } else {
    const { libraries, dirs, packages, missing } = builderLibraryClosure();
    const total = dirs.reduce(
      (acc, dir) => {
        const size = dirSize(path.join(ROOT, dir));
        return { bytes: acc.bytes + size.bytes, files: acc.files + size.files };
      },
      { bytes: 0, files: 0 },
    );
    console.log(`${libraries.length} libraries → ${dirs.length} package folders, ${(total.bytes / 1e6).toFixed(1)} MB, ${total.files} files`);
    console.log(`${unpackPatterns(packages).length} asarUnpack patterns; not installed (optional/peer): ${missing.join(', ') || 'none'}`);
  }
}
